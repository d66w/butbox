create or replace function public.create_box(p_space_id uuid, p_name text)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_name text := btrim(coalesce(p_name, ''));
  v_order integer;
  v_box_id uuid;
begin
  if not public.is_space_member(p_space_id) then
    raise exception 'NOT_SPACE_MEMBER';
  end if;
  if char_length(v_name) < 1 or char_length(v_name) > 40 then
    raise exception 'INVALID_BOX_NAME';
  end if;

  select coalesce(max(sort_order), -1) + 1 into v_order from public.boxes where space_id = p_space_id;

  insert into public.boxes (space_id, name, kind, sort_order)
  values (p_space_id, v_name, 'text', v_order)
  returning id into v_box_id;

  return v_box_id;
end;
$$;

create or replace function public.reorder_boxes(p_space_id uuid, p_box_ids uuid[])
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_space_member(p_space_id) then
    raise exception 'NOT_SPACE_MEMBER';
  end if;
  update public.boxes b
  set sort_order = ordered.idx - 1
  from unnest(p_box_ids) with ordinality as ordered(box_id, idx)
  where b.id = ordered.box_id and b.space_id = p_space_id;
end;
$$;

