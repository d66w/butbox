create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  display_name text,
  plan text not null default 'free' references public.plans(code),
  plan_expires_at timestamptz,
  extra_spaces integer not null default 0 check (extra_spaces >= 0),
  extra_boxes integer not null default 0 check (extra_boxes >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.spaces (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(name) between 1 and 40),
  space_code text not null unique check (space_code ~ '^[A-Z0-9][A-Z0-9-]{2,23}$'),
  password_hash text,
  owner_id uuid not null references public.profiles(id) on delete restrict,
  box_limit integer not null default 10 check (box_limit > 0),
  quota_bytes bigint not null default 52428800 check (quota_bytes > 0),
  used_bytes bigint not null default 0 check (used_bytes >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.space_members (
  space_id uuid not null references public.spaces(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role text not null default 'member' check (role in ('owner', 'member')),
  joined_at timestamptz not null default now(),
  primary key (space_id, user_id)
);

create index if not exists space_members_user_idx on public.space_members (user_id, joined_at);

create table if not exists public.boxes (
  id uuid primary key default gen_random_uuid(),
  space_id uuid not null references public.spaces(id) on delete cascade,
  name text not null check (char_length(name) between 1 and 40),
  kind text not null default 'text' check (kind in ('text', 'image', 'file')),
  text_content text,
  r2_key text,
  byte_size bigint not null default 0 check (byte_size >= 0),
  expires_at timestamptz,
  sort_order integer not null default 0,
  locked boolean not null default false,
  updated_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint boxes_text_size check (text_content is null or octet_length(text_content) <= 10240),
  constraint boxes_kind_shape check (
    (kind = 'text' and r2_key is null and expires_at is null)
    or (kind in ('image', 'file') and text_content is null)
  )
);

create index if not exists boxes_space_order_idx on public.boxes (space_id, sort_order, created_at);

create table if not exists public.upgrade_intents (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  space_id uuid references public.spaces(id) on delete set null,
  lever text not null check (lever in ('box_limit', 'space_quota', 'space_limit', 'file_upload')),
  created_at timestamptz not null default now()
);

create index if not exists upgrade_intents_user_idx on public.upgrade_intents (user_id, created_at desc);

