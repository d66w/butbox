    );
  insert into public.analytics_events (user_id, event, props)
  values (v_user, p_event, v_props);
exception
  when check_violation then
    return;
end;
$$;

create or replace function public.set_member_role(p_space_id uuid, p_user_id uuid, p_role text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_actor_role text;
begin
  select role into v_actor_role from public.space_members
  where space_id = p_space_id and user_id = auth.uid();

  if v_actor_role is null or v_actor_role not in ('owner', 'admin') then
    raise exception 'NOT_SPACE_ADMIN';
  end if;
  if p_role not in ('admin', 'member') then
    raise exception 'INVALID_ROLE';
  end if;
  if p_user_id = auth.uid() then
    raise exception 'CANNOT_CHANGE_OWN_ROLE';
  end if;
  if exists (
    select 1 from public.space_members
    where space_id = p_space_id and user_id = p_user_id and role = 'owner'
  ) then
    raise exception 'CANNOT_CHANGE_OWNER_ROLE';
  end if;
  if v_actor_role = 'admin' and p_role = 'admin' then
    raise exception 'NOT_SPACE_OWNER';
  end if;

  update public.space_members set role = p_role
  where space_id = p_space_id and user_id = p_user_id;
end;
$$;

create or replace function public.create_invite(p_space_id uuid, p_role text, p_days integer)
returns text
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_actor_role text;
  v_token text;
  v_days integer := least(greatest(coalesce(p_days, 7), 1), 30);
  v_role text := coalesce(p_role, 'member');
  attempts integer := 0;
begin
  select role into v_actor_role from public.space_members
  where space_id = p_space_id and user_id = auth.uid();
  if v_actor_role is null or v_actor_role not in ('owner', 'admin') then
    raise exception 'NOT_SPACE_ADMIN';
  end if;
  if v_role not in ('admin', 'member') then
    raise exception 'INVALID_ROLE';
  end if;
  if v_role = 'admin' and v_actor_role <> 'owner' then
    raise exception 'NOT_SPACE_OWNER';
  end if;

  loop
    v_token := encode(gen_random_bytes(18), 'hex');
    exit when not exists (select 1 from public.invitations where token = v_token);
    attempts := attempts + 1;
    if attempts > 30 then
      raise exception 'INVITE_TOKEN_EXHAUSTED';
    end if;
  end loop;

  insert into public.invitations (token, space_id, created_by, role, expires_at)
  values (v_token, p_space_id, auth.uid(), v_role, now() + make_interval(days => v_days));

  return v_token;
end;
$$;

create or replace function public.peek_invite(p_token text)
returns table (space_name text, member_count bigint, expired boolean)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_inv public.invitations;
begin
  select * into v_inv from public.invitations where token = btrim(coalesce(p_token, ''));
  if not found then
    raise exception 'INVITE_NOT_FOUND';
  end if;
  return query
  select s.name,
         (select count(*) from public.space_members m where m.space_id = s.id),
         (v_inv.expires_at <= now() or v_inv.uses >= v_inv.max_uses)
  from public.spaces s
  where s.id = v_inv.space_id;
end;
$$;

create or replace function public.redeem_invite(p_token text)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_inv public.invitations;
begin
  if v_user is null then
    raise exception 'NOT_AUTHENTICATED';
  end if;
  perform public.current_profile();

  select * into v_inv from public.invitations where token = btrim(coalesce(p_token, '')) for update;
  if not found then
    raise exception 'INVITE_NOT_FOUND';
  end if;
  if v_inv.expires_at <= now() then
    raise exception 'INVITE_EXPIRED';
  end if;
  if v_inv.uses >= v_inv.max_uses then
    raise exception 'INVITE_EXHAUSTED';
  end if;

  if exists (select 1 from public.space_members where space_id = v_inv.space_id and user_id = v_user) then
    return v_inv.space_id;
  end if;

  insert into public.space_members (space_id, user_id, role)
  values (v_inv.space_id, v_user, v_inv.role)
  on conflict (space_id, user_id) do nothing;

  update public.invitations set uses = uses + 1 where token = v_inv.token;

  return v_inv.space_id;
end;
$$;

