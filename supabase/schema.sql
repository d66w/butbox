create or replace function public.create_space(p_name text)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_profile public.profiles;
  v_plan public.plans;
  v_owned integer;
  v_name text := btrim(coalesce(p_name, ''));
  v_space_id uuid;
begin
  if v_user is null then
    raise exception 'NOT_AUTHENTICATED';
  end if;
  if char_length(v_name) < 1 or char_length(v_name) > 40 then
    raise exception 'INVALID_SPACE_NAME';
  end if;

  v_profile := public.current_profile();
  select * into v_plan from public.plans where code = v_profile.plan;
  select count(*) into v_owned from public.spaces where owner_id = v_user;

  if v_owned >= v_plan.space_limit + v_profile.extra_spaces then
    raise exception 'SPACE_LIMIT_REACHED';
  end if;

  insert into public.spaces (name, space_code, owner_id, box_limit, quota_bytes)
  values (
    v_name,
    public.generate_space_code(),
    v_user,
    v_plan.box_limit + v_profile.extra_boxes,
    v_plan.quota_bytes
  )
  returning id into v_space_id;

  insert into public.space_members (space_id, user_id, role)
  values (v_space_id, v_user, 'owner');

  return v_space_id;
end;
$$;

create or replace function public.ensure_personal_space()
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_space_id uuid;
begin
  if v_user is null then
    raise exception 'NOT_AUTHENTICATED';
  end if;
  perform public.current_profile();

  select id into v_space_id from public.spaces where owner_id = v_user order by created_at limit 1;
  if v_space_id is not null then
    insert into public.space_members (space_id, user_id, role)
    values (v_space_id, v_user, 'owner')
    on conflict (space_id, user_id) do nothing;
    return v_space_id;
  end if;

  select space_id into v_space_id from public.space_members where user_id = v_user order by joined_at limit 1;
  if v_space_id is not null then
    return v_space_id;
  end if;

  return public.create_space('내 공간');
end;
$$;

