create or replace function public.set_space_code(p_space_id uuid, p_code text)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_code text := upper(btrim(coalesce(p_code, '')));
begin
  if not public.is_space_owner(p_space_id) then
    raise exception 'NOT_SPACE_OWNER';
  end if;
  if v_code !~ '^[A-Z0-9][A-Z0-9-]{3,23}$' then
    raise exception 'INVALID_SPACE_CODE';
  end if;
  if exists (select 1 from public.spaces where space_code = v_code and id <> p_space_id) then
    raise exception 'SPACE_CODE_TAKEN';
  end if;
  update public.spaces set space_code = v_code, updated_at = now() where id = p_space_id;
  return v_code;
end;
$$;

create or replace function public.set_space_password(p_space_id uuid, p_password text)
