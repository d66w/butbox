create or replace function public.generate_space_code()
returns text
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  alphabet constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  raw text;
  candidate text;
  attempts integer := 0;
begin
  loop
    raw := '';
    for i in 1..8 loop
      raw := raw || substr(alphabet, 1 + floor(random() * length(alphabet))::integer, 1);
    end loop;
    candidate := substr(raw, 1, 4) || '-' || substr(raw, 5, 4);
    exit when not exists (select 1 from public.spaces s where s.space_code = candidate);
    attempts := attempts + 1;
    if attempts > 50 then
      raise exception 'SPACE_CODE_EXHAUSTED';
    end if;
  end loop;
  return candidate;
end;
$$;

create or replace function public.boxes_before_write()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_space public.spaces;
  v_delta bigint;
begin
  if tg_op = 'UPDATE' then
    if old.locked and new.text_content is distinct from old.text_content then
      raise exception 'BOX_LOCKED';
    end if;
    new.space_id := old.space_id;
    new.kind := old.kind;
    new.locked := old.locked;
    new.created_at := old.created_at;
  end if;

  if new.kind = 'text' then
    new.r2_key := null;
    new.expires_at := null;
    new.byte_size := coalesce(octet_length(new.text_content), 0);
  end if;

  new.updated_at := now();
  new.updated_by := auth.uid();

  select * into v_space from public.spaces where id = new.space_id for update;
  if not found then
    raise exception 'SPACE_NOT_FOUND';
  end if;

  if tg_op = 'INSERT' then
    v_delta := new.byte_size;
  else
    v_delta := new.byte_size - old.byte_size;
  end if;

  if v_delta > 0 and v_space.used_bytes + v_delta > v_space.quota_bytes then
    raise exception 'SPACE_QUOTA_EXCEEDED';
  end if;

  return new;
end;
$$;

drop trigger if exists boxes_before_write on public.boxes;
create trigger boxes_before_write before insert or update on public.boxes
for each row execute function public.boxes_before_write();

create or replace function public.boxes_sync_usage()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    update public.spaces
    set used_bytes = used_bytes + new.byte_size, updated_at = now()
    where id = new.space_id;
    return new;
  elsif tg_op = 'UPDATE' then
    if new.space_id = old.space_id then
      update public.spaces
      set used_bytes = greatest(0, used_bytes + (new.byte_size - old.byte_size)), updated_at = now()
      where id = new.space_id;
    else
      update public.spaces
      set used_bytes = greatest(0, used_bytes - old.byte_size), updated_at = now()
      where id = old.space_id;
      update public.spaces
      set used_bytes = used_bytes + new.byte_size, updated_at = now()
      where id = new.space_id;
    end if;
    return new;
  else
    update public.spaces
    set used_bytes = greatest(0, used_bytes - old.byte_size), updated_at = now()
    where id = old.space_id;
    return old;
  end if;
end;
$$;

drop trigger if exists boxes_sync_usage on public.boxes;
create trigger boxes_sync_usage after insert or update or delete on public.boxes
for each row execute function public.boxes_sync_usage();

create or replace function public.enforce_box_limit()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_limit integer;
  v_count integer;
begin
  select box_limit into v_limit from public.spaces where id = new.space_id;
  select count(*) into v_count from public.boxes where space_id = new.space_id;
  if v_count >= v_limit then
    raise exception 'BOX_LIMIT_REACHED';
  end if;
  return new;
end;
$$;

