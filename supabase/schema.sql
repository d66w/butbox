create or replace function public.normalize_tags(p_tags text[], p_limit integer)
returns text[]
language plpgsql
immutable
as $$
declare
  v_tag text;
  v_clean text;
  v_out text[] := '{}';
begin
  if p_tags is null then
    return v_out;
  end if;
  foreach v_tag in array p_tags loop
    v_clean := btrim(regexp_replace(coalesce(v_tag, ''), '\s+', ' ', 'g'));
    if char_length(v_clean) between 1 and 16 and not (v_clean = any (v_out)) then
      v_out := array_append(v_out, v_clean);
    end if;
    if array_length(v_out, 1) >= p_limit then
      exit;
    end if;
  end loop;
  return v_out;
end;
$$;

